import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import YAML from 'yaml'
import { loadReviews, reviewCoverage } from './review-lib.mjs'
import { loadPapers } from './content-lib.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const baseline = JSON.parse(await fs.readFile(path.join(root, 'data/reviews/baseline.json'), 'utf8'))
const reviews = await loadReviews(root)
if (reviews.size !== baseline.paper_ids.length || baseline.paper_ids.some(id => !reviews.has(id))) throw new Error('Review roster differs from the frozen baseline')
// Completion and synchronization must validate the actual current notes too.
const papers = await loadPapers(root)
if (papers.length !== reviews.size || papers.some(paper => reviews.get(paper.id)?.note_path !== paper.note_path)) throw new Error('Review notes differ from the frozen roster or registered paths')
let round
try { round = JSON.parse(await fs.readFile(path.join(root, 'data/reviews/current-round.json'), 'utf8')) } catch (error) { if (error.code !== 'ENOENT') throw error }
let conferenceBatch
try { conferenceBatch = JSON.parse(await fs.readFile(path.join(root, 'data/imports/conference-163-2026-11-17.json'), 'utf8')) } catch (error) { if (error.code !== 'ENOENT') throw error }
if (round && [...reviews.values()].some(review => review.round_id !== round.id)) throw new Error('Review record belongs to a different review round')
async function atomicWrite(filename, contents) {
  const destination = path.join(root, filename)
  const temporary = `${destination}.${process.pid}.tmp`
  await fs.writeFile(temporary, contents)
  await fs.rename(temporary, destination)
}
const counts = { pending: 0, reading: 0, verified: 0, blocked: 0 }
for (const record of reviews.values()) counts[record.status]++
if (process.argv.includes('--require-complete') && counts.verified !== reviews.size) throw new Error(`Full-text review is incomplete: ${counts.verified}/${reviews.size} verified`)
const relations = []
const pairs = new Set()
for (const review of reviews.values()) {
  if (review.status !== 'verified') continue
  for (const citation of review.citations) {
    if (!reviews.has(citation.cited)) throw new Error(`${review.paper_id}: citation target is outside the frozen collection`)
    const key = `${citation.citing}::${citation.cited}`
    if (pairs.has(key)) throw new Error(`Duplicate directed citation ${key}`)
    pairs.add(key)
    relations.push(citation)
  }
}
relations.sort((a, b) => a.citing.localeCompare(b.citing) || a.cited.localeCompare(b.cited))
const relationsOutput = '# Verified, directed, in-text citations. Generated by npm run review:sync.\n' + YAML.stringify({ relations })

// Keep the initial automated discovery inventory distinct from completed human review.
let supplementInventory = {}
try { supplementInventory = JSON.parse(await fs.readFile(path.join(root, 'data/reviews/supplement-inventory.json'), 'utf8')) } catch (error) { if (error.code !== 'ENOENT') throw error }
for (const paper of papers) {
  const review = reviews.get(paper.id)
  const item = supplementInventory[paper.id] ?? { publication_url: paper.paper_url, links: [], discovery_status: 'See manual source inventory in the review record.' }
  item.publication_url = paper.paper_url
  item.manual_verification_complete = review.status === 'verified' && review.supplements_checked
  item.manual_review_record = `data/reviews/papers/${paper.id}.json`
  item.manual_evidence = review.metadata_evidence.filter(evidence => /supplement/i.test(evidence.field))
  supplementInventory[paper.id] = item
}

const dispositions = baseline.original_relations.map((relation, index) => {
  const [a, b] = relation.papers
  const retained = relations.filter(item => (item.citing === a && item.cited === b) || (item.citing === b && item.cited === a))
  const checked = reviews.get(a)?.citation_scan_complete && reviews.get(b)?.citation_scan_complete
  return { baseline_index: index, original: relation, status: retained.length ? 'supported_by_explicit_citation' : checked ? 'removed' : 'pending', reason: retained.length ? 'Explicit in-text citation evidence is recorded in the directed graph.' : checked ? 'No explicit in-text citation between these papers was established in the reviewed versions.' : 'Full citation scans are not yet complete for both endpoints.' }
})
const statusLabels = { pending: '待精读', reading: '精读中', verified: '全文复核通过', blocked: '原文或事实问题未解决' }
const sourceCoverage = [...reviews.values()].flatMap(reviewCoverage)
const readPages = sourceCoverage.reduce((total, source) => total + source.read_pages, 0)
const registeredPages = sourceCoverage.reduce((total, source) => total + source.total_pages, 0)
const lines = [
  '# 全仓全文复核进度', '',
  `冻结范围：**${reviews.size} 篇**；原有关联：**${baseline.original_relations.length} 条**；截止日期：**${baseline.cutoff}**。`, '',
  ...(round ? [`当前轮次：**${round.id}**。上轮证据已归档，本轮仅统计重新精读、核验通过的条目。`, ''] : []),
  `全文复核通过 **${counts.verified}**，精读中 **${counts.reading}**，待精读 **${counts.pending}**，阻塞 **${counts.blocked}**。`, '',
  ...(conferenceBatch ? [`本次会议候选 **${conferenceBatch.requested_papers} 篇**；已完成新增 **${conferenceBatch.completed_papers} 篇**；另有 **${conferenceBatch.deferred_papers} 篇**按用户规则保留在[待补清单](conference-163-deferred-2026-11-17.md)，不计入活动复核范围或已完成新增。`, ''] : []),
  `已记录实际阅读 **${readPages} / ${registeredPages} 页**（正文、参考文献及已登记科学附录／补充材料）；**${papers.filter(paper => paper.figure).length} 篇**附有核对过的原论文图。`, '',
  '页数按登记的阅读副本累加，包含版本重合、随附学术报告以及明确标识的本地来源渲染，并非互不重复的正式正文页数。', '',
  `已建立原文证据的有向内部引用：**${relations.length} 条**。原有主题关系不作为已验证引用展示。`, '',
  '## 完成标准', '',
  '- 阅读完整正文、附录及补充材料，记录连续页码覆盖；下载和文本提取不计作已读。',
  '- 核对版本与身份，关键事实有页码或官方出版记录定位，图表与笔记完成反向对照。',
  '- 正式全文不可获取时可使用明确标识的 arXiv 版本；阅读副本与正式发表资格分别核验。',
  '- 人工核查科学补充材料，包括 ZIP 内附件及 OpenReview 单独附件；没有额外附件也必须记录检查依据。',
  '- 扫描参考文献并核对实际引用位置；主题相似、仅列入书目均不能代替正文引用证据。',
  '- 未解决问题必须保留；存在阻塞或遗漏页码的论文不得标记为通过。', '',
  '## 逐篇状态', '',
  '| 论文 ID | 状态 | 已读／原文页数 | 修改数 | 未解决项 | 记录 |',
  '| --- | --- | ---: | ---: | ---: | --- |',
]
for (const id of baseline.paper_ids) {
  const review = reviews.get(id)
  const coverage = reviewCoverage(review)
  const read = coverage.reduce((n, item) => n + item.read_pages, 0)
  const total = coverage.reduce((n, item) => n + item.total_pages, 0)
  lines.push(`| [${id}](../${review.note_path}) | ${statusLabels[review.status]} | ${read} / ${total || '未取得'} | ${review.corrections.length} | ${review.issues.length} | [证据](../data/reviews/papers/${id}.json) |`)
}
lines.push('', '## 工作方式', '',
  '原文缓存保存在本地 `research/`，不提交 PDF。逐篇证据与阅读进度提交到 `data/reviews/`。',
  '运行 `npm run review:sync` 更新本页和引用图；运行 `npm run review:complete` 检查是否全部完成。',
  '格式检查与测试通过只证明数据及界面符合约束，不代替学术事实核验。', '')
if (counts.verified === reviews.size) lines.push('本轮收尾记录：[文件与页面验证](../data/reviews/completion-audit.json)、[引用身份交叉检查](../data/reviews/citation-crosscheck-audit.json)、[发表与预印本日期核验](../data/reviews/publication-date-audit.json)。', '')
// Prepare all outputs before replacing any destination; each replacement is atomic.
await atomicWrite('data/relations.yml', relationsOutput)
await atomicWrite('data/reviews/supplement-inventory.json', JSON.stringify(supplementInventory, null, 2) + '\n')
await atomicWrite('data/reviews/relation-dispositions.json', JSON.stringify(dispositions, null, 2) + '\n')
await atomicWrite('docs/FULL_TEXT_REVIEW.md', lines.join('\n'))
console.log(`Full-text review: ${counts.verified}/${reviews.size} verified; ${counts.reading} reading; ${relations.length} supported citations.`)
